from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORT_PATH = ROOT / "docs" / "component-doc-coverage.md"
REPORT_BASE = REPORT_PATH.parent

EXCLUDE_DIRS = {
    ".git",
    ".github",
    ".venv",
    ".pytest_cache",
    "__pycache__",
}


@dataclass
class ComponentRow:
    component: str
    readme_path: str
    doc_type: str
    generated_by: str
    status: str


def markdown_link_for(path_str: str, base_dir: Path = REPORT_BASE) -> str:
    target_path = ROOT / path_str
    relative_target = target_path.relative_to(ROOT)
    up_prefix = "../"
    if base_dir != ROOT:
        up_prefix = "../" * len(base_dir.relative_to(ROOT).parts)
    rendered_target = f"{up_prefix}{relative_target.as_posix()}"
    return f"[{path_str}]({rendered_target})"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate OSCO component documentation coverage report")
    parser.add_argument("--write", action="store_true", help="Write report to docs/component-doc-coverage.md")
    parser.add_argument("--check", action="store_true", help="Fail on missing docs or stale report")
    return parser.parse_args()


def list_components() -> list[Path]:
    components: list[Path] = []

    # Top-level components (excluding hidden and build/cache directories).
    for child in sorted(ROOT.iterdir()):
        if not child.is_dir():
            continue
        if child.name in EXCLUDE_DIRS:
            continue
        if child.name.endswith(".egg-info"):
            continue
        components.append(child)

    # SDK language subcomponents.
    sdk_dir = ROOT / "sdk"
    if sdk_dir.exists():
        for child in sorted(sdk_dir.iterdir()):
            if child.is_dir() and child.name not in EXCLUDE_DIRS:
                components.append(child)

    # Python package subcomponents.
    package_dir = ROOT / "osco"
    if package_dir.exists():
        for child in sorted(package_dir.iterdir()):
            if child.is_dir() and child.name not in EXCLUDE_DIRS:
                components.append(child)

    # De-duplicate while preserving sort order.
    deduped: list[Path] = []
    seen: set[str] = set()
    for item in components:
        rel = str(item.relative_to(ROOT))
        if rel in seen:
            continue
        seen.add(rel)
        deduped.append(item)

    return deduped


def detect_doc_type(readme_path: Path) -> tuple[str, str]:
    if not readme_path.exists():
        return "missing", ""

    text = readme_path.read_text().lower()
    if "auto-generated" in text or "auto generated" in text:
        return "generated", "scripts/generate_capability_table.py"

    return "manual", ""


def build_rows() -> list[ComponentRow]:
    rows: list[ComponentRow] = []
    for component_dir in list_components():
        rel_component = str(component_dir.relative_to(ROOT))
        readme = component_dir / "README.md"
        doc_type, generated_by = detect_doc_type(readme)
        status = "ok" if readme.exists() else "missing"
        rows.append(
            ComponentRow(
                component=rel_component,
                readme_path=str(readme.relative_to(ROOT)),
                doc_type=doc_type,
                generated_by=generated_by,
                status=status,
            )
        )
    return rows


def render_report(rows: list[ComponentRow]) -> str:
    missing = [row for row in rows if row.status == "missing"]
    generated = [row for row in rows if row.doc_type == "generated"]

    lines = [
        "# Component Documentation Coverage",
        "",
        "This report is auto-generated by [scripts/generate_component_docs_report.py](../scripts/generate_component_docs_report.py).",
        "",
        f"- Components checked: {len(rows)}",
        f"- Components documented: {len(rows) - len(missing)}",
        f"- Components missing docs: {len(missing)}",
        f"- Generated component docs: {len(generated)}",
        "",
        "## Coverage Table",
        "",
        "| Component | README | Doc Type | Generated By | Status |",
        "|---|---|---|---|---|",
    ]

    for row in rows:
        component_link = markdown_link_for(row.component)
        readme_link = markdown_link_for(row.readme_path)
        generated_link = markdown_link_for(row.generated_by) if row.generated_by else ""
        lines.append(
            "| "
            + " | ".join(
                [
                    component_link,
                    readme_link,
                    row.doc_type,
                    generated_link,
                    row.status,
                ]
            )
            + " |"
        )

    if missing:
        lines.extend(["", "## Missing Components", ""])
        for row in missing:
            lines.append(f"- {row.component}")

    lines.append("")
    return "\n".join(lines)


def main() -> None:
    args = parse_args()
    rows = build_rows()
    report = render_report(rows)

    if args.write:
        REPORT_PATH.write_text(report)
        print(f"Wrote report to {REPORT_PATH}")

    if args.check:
        missing = [row for row in rows if row.status == "missing"]
        if missing:
            print("Missing component docs detected:")
            for row in missing:
                print(f"- {row.component}")
            raise SystemExit(1)

        existing = REPORT_PATH.read_text() if REPORT_PATH.exists() else ""
        if existing != report:
            print("Component docs report is out of date. Run with --write.")
            raise SystemExit(1)

        print("Component documentation coverage check passed.")


if __name__ == "__main__":
    main()
